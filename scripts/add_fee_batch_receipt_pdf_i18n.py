def php_escape(value: str) -> str:
    return value.replace("\\", "\\\\").replace("'", "\\'")


def main() -> None:
    for locale, additions in KEYS.items():
        path = LANG / locale / "pdf.php"
        text = path.read_text(encoding="utf-8")
        if "edu_fee_batch_receipt_title" in text:
            print(f"{locale}: déjà présent, ignoré")
            continue

        block = ["\n    // #9793 — reçu PDF d'un encaissement en lot."]
        for key, value in additions.items():
            block.append(f"    '{key}' => '{php_escape(value)}',")
        block.append("")

        # Insère avant le `];` final.
        idx = text.rstrip().rfind("];")
        if idx == -1:
            raise SystemExit(f"{path}: fermeture de tableau introuvable")
        new_text = text[:idx] + "\n".join(block) + text[idx:]
        path.write_text(new_text, encoding="utf-8")
        print(f"{locale}: {len(additions)} clés ajoutées")


if __name__ == "__main__":
    main()
