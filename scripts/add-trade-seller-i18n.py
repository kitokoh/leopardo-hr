def main() -> None:
    for code in ("fr", "en", "ar", "tr"):
        path = LOCALES / f"{code}.json"
        data = json.loads(path.read_text(encoding="utf-8"))
        trade = data.setdefault("trade", {})

        trade["profile"] = PROFILE[code]
        trade["documents"] = DOCUMENTS[code]
        trade["promotion"] = PROMOTION[code]

        path.write_text(
            json.dumps(data, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
        print(f"{code}: profile={len(PROFILE[code])} documents={len(DOCUMENTS[code])} promotion={len(PROMOTION[code])}")


if __name__ == "__main__":
    main()
