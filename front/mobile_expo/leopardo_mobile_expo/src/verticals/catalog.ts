/** Retrouve un module par sa cle. */
export function moduleByKey(key: ClientModuleKey): ClientModule | undefined {
  return CLIENT_MODULES.find((module) => module.key === key);
}

/** Retrouve la verticale d'un module metier. */
export function verticalForModule(key: ClientModuleKey): BusinessVertical | undefined {
  return moduleByKey(key)?.vertical;
}

/** Modules d'une verticale, dans l'ordre du catalogue. */
export function modulesForVertical(vertical: BusinessVertical): ClientModule[] {
  return CLIENT_MODULES.filter((module) => module.vertical === vertical);
}
